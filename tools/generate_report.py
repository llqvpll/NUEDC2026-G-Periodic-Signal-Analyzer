add_title("2.2 基频测量：GCD最大公约数法", level=2)
add_para(
    "本题基频测量的核心难点在于：周期信号可能包含多种谐波组合，"
    "基波分量幅值可能小于高次谐波——若简单地取最大谱峰对应频率作为基频，将产生严重错误。"
    "例如赛题说明中的例子：谱线频率为10.5kHz、31.5kHz、42.0kHz，"
    "若取最大峰（42kHz）作为基频，则31.5kHz无法被解释为整数次谐波，显然错误。"
)
add_para(
    "本方案采用GCD最大公约数法，步骤如下："
    "（1）在幅度谱中检测所有显著谱峰（幅值超过阈值的局部极大值点）；"
    "（2）以最低谱峰频率f_min作为候选基频；"
    "（3）穷举k=1~20，校验是否存在k使|f_candidate − f_peak/k|<容差（0.5×bin宽度）对所有谱峰成立；"
    "（4）若校验通过，f_candidate即为基频；若不通过，取f_candidate=f_min/k_min重复步骤（3）；"
    "（5）最终通过抛物线三点插值将频率精度提升至<10Hz级别。"
)
add_para(
    "以赛题示例验证：谱峰f1=10.5k, f2=31.5k, f3=42.0k。"
    "设f_candidate=10.5k，校验：42.0k/4=10.5k（通过），31.5k/3=10.5k（通过），基频=10.5kHz，正确。"
    "若基波分量很小（如10.5kHz处峰值低于阈值），只要其二次/三次等高次谐波被检出，"
    "GCD法仍能从高阶谐波反推出正确的基频——这是本算法的核心优势。"
)

add_title("2.3 谐波幅值：Hanning-DTFT插值法", level=2)
add_para(
    "FFT谱线中栅栏效应是幅值测量的最大误差来源：当谐波频率不恰好落在整数bin上时，"
    "峰值bin的幅值会因频谱泄漏而偏低。本方案采用两步策略。"
)
add_para(
    "第一步——窗口选择：采用Hanning窗（旁瓣-31dB）。"
    "题目最低谐波间隔10kHz，对应约20个bin（2MHz/4096=488Hz/bin），各次谐波互不泄漏。"
    "Hanning窗的计算通过预存储窗表（4096点float，占16KB CCM）实现查表乘法，"
    "避免每次FFT前耗时的cosf实时计算（节省约2~3ms）。"
)
add_para(
    "第二步——DTFT插值：在已知基频f1后，对各次谐波频率点k×f1直接计算DTFT（离散时间傅里叶变换），"
    "而非依赖FFT bin的离散频率点。DTFT的幅度响应公式为："
    "|H(f)| = |Σ x[n]·w[n]·exp(−j2π·f·n/fs)|，"
    "其中x[n]为原始采样序列，w[n]为Hanning窗函数，f为精确谐波频率，fs为采样率。"
    "计算后除以窗函数相干增益（g_winsum = N/2）即可得到精确幅值。"
    "在谐波间隔≥20bin的条件下，幅值误差<0.2%，远优于题目5mV指标。"
    "Item3中还需乘以FIR滤波器在谐波频率处的|H(f)|修正值，补偿数字滤波的通带衰减。"
)

add_title("2.4 时域参数：整周期真有效值与峰峰值", level=2)
add_para(
    "在测得基频f1后，按照整数个完整周期截取采样序列，消除截断误差。"
    "截取点数M = round(Ncycle × fs / f1)，其中Ncycle取整数周期数。"
)
add_para(
    "真有效值Urms = √(1/M × Σ x[i]²)，定义法对任何波形失真均正确，无需假设波形为正弦。"
    "峰峰值Upp的测量采用多周期平均法：在每个周期内取max−min，多个周期的结果取平均，"
    "有效抑制随机噪声引起的峰值虚高。此外取峰值/谷值附近各5个采样点的均值作为局部极值，"
    "进一步压制毛刺干扰。"
)
add_para(
    "Item3中，采样数据先经127阶数字FIR（fc=600kHz，阻带-60dB@≥1MHz）"
    "滤波+4倍抽取后再行计算，确保ub的单频干扰被充分抑制后获得干净参数。"
)

add_title("2.5 Item3干扰抑制：模拟+数字双级滤波器设计", level=2)
add_para(
    "Item3要求在被测信号ub（≤500kHz）上叠加≥1MHz/200mVpp单频干扰uJ的条件下，"
    "准确测量ub的各项参数。抑制策略分为两级。"
)
add_para(
    "第一级——模拟域（UFA42 750kHz LPF）：1MHz处衰减约-18dB（200mV→25mV），"
    "防止高频大信号使后级OPA847和AD9240饱和。"
    "若没有此级，200mVpp的1MHz信号直入放大器后再入ADC，不仅使运放/ADC超量程，"
    "更严重的是若fJ落在采样率的混叠带内（如4.5MHz采4.8MHz时混叠至300kHz），"
    "将产生一个300kHz的虚假信号——恰好在ub频带内，数字滤波无法区分。"
    "模拟LPF在采样前压制所有>2.5MHz的混叠风险，是数字滤波的基础前提。"
)
add_para(
    "第二级——数字域：127阶等波纹FIR低通滤波器，fc=600kHz，通带纹波<0.1dB，≥1MHz处阻带衰减-60dB。"
    "Item3采集16384点（实际16528点含FIR群延迟填充）@4.8MHz，"
    "滤波后4倍抽取至4096点@1.2MHz（频率分辨率293Hz）。"
    "双级级联总衰减约78dB（200mV→0.025mV），uJ的频谱分量在最终结果中完全不可见。"
    "FIR采用CMSIS-DSP库arm_fir_decimate_f32实现（内部循环展开+FPU优化），"
    "16384点×127阶的滤波+抽取耗时约2ms，远低于2s限时。"
)

