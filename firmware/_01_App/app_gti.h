#ifndef __APP_GTI_H
#define __APP_GTI_H

#include "User_header.h"

/* ------------------------- 系统常数 (按硬件实际值) ------------------------- */
#define GTI_ADC_GAIN        5.0f        /* OPA847 固定增益 (Rf/Rg = 1k/200) */
#define GTI_ADC_VREF        2.5f        /* AD9240 满量程 0-2.5V */
#define GTI_ADC_CODES       16384.0f    /* 14bit */

/* 幅值校准系数: 含模块内部衰减修正
 * 实测: 200mV输入显示~330mV => CAL=200/330≈0.6
 * 精调: 输入标准信号, GTI_CAL = 真实mV / 显示mV * 当前值
 */
#define GTI_CAL             0.600f

/* 码 -> 输入端 mV 换算: (code * Vref/16384) / 5 * 1000mV * CAL */
#define GTI_CODE_TO_MV(c)   ((float)(c) * (GTI_ADC_VREF / GTI_ADC_CODES) / GTI_ADC_GAIN * 1000.0f * GTI_CAL)

/* ------------------------- 对外接口 ------------------------- */

/* G题模式主入口: 初始化 + 主循环 (按 NumLock 退出返回旧菜单) */
void GTI_Run(void);

#endif
